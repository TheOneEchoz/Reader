  if ((m = sh.match(/DynamicImage '([^']+)': could not find image/)) && /\[[A-Za-z_][\w.]*\]/.test(m[1])) { kind = 'dynimg'; tpl = m[1]; name = m[1].match(/\[([A-Za-z_][\w.]*)\]/)[1]; }
