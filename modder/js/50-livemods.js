async function liveMods(gid) {
  const g = await S.gal(gid), mods = g.game.mods || [], want = new Map(mods.map(m => [m.id, m.on]));
  const go1 = h('button', { class: 'btn primary', id: 'livemods-go', disabled: true, onclick: async () => {
    go1.disabled = true; go1.lastChild.textContent = 'Saving…';
    const saved = await gameAutosave();
    for (const m of mods) if (want.get(m.id) !== m.on) await setModOn(gid, m.id, want.get(m.id));
    closeSheet(); closeGame();
    if (!saved) toast('The game could not be saved first, so it starts from your newest save.', 4000);
    CUR.params = { id: gid, cont: 1 }; render('game', { id: gid, cont: 1 });
  } }, icon('play'), h('span', {}, 'Restart with these mods'));
  const rows = mods.map(m => h('div', { class: 'row modrow', style: 'justify-content:space-between;gap:10px' }, h('b', {}, m.name),
    h('button', { class: 'switch', role: 'switch', 'aria-checked': String(m.on), 'aria-label': `Use the mod ${m.name}`, onclick: e => { want.set(m.id, !want.get(m.id)); e.currentTarget.setAttribute('aria-checked', String(want.get(m.id))); go1.disabled = mods.every(x => want.get(x.id) === x.on); } })));
  openSheet('Mods', h('div', { class: 'stack', id: 'livemods' }, ...rows, go1,
    h('p', { class: 'hint' }, 'Ren\'Py reads a game\'s mods only when it starts. The game is saved, started again with these mods, and put back where you are; it takes a few seconds. A mod that changes the scene you are in may not load that save well: then load an earlier save.')));
}
