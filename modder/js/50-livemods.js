/* ask the running Ren'Py game something (Python; the answer is what it puts in `result`) */
function gamePy(code, ms = 8000) {
  return new Promise(res => {
    if (!GAME.frame || !GAME.loaded) return res(null);
    GAME.pyq = GAME.pyq || new Map(); const q = Math.random().toString(36).slice(2);
    const t = setTimeout(() => { GAME.pyq.delete(q); res(null); }, ms);
    GAME.pyq.set(q, m => { clearTimeout(t); res(m.err ? null : m.result); });
    GAME.frame.contentWindow.postMessage({ t: 'pyq', q, code }, '*');
  });
}
